import assert from 'node:assert/strict';
import {canSee,validateRecord} from './server/hub-rules.ts';
const student={id:'s1',groupId:'g1'},ctx={userId:'u1',admin:false,owner:false,student};
assert.equal(canSee({kind:'invoices',studentId:'s2'},ctx),false);
assert.equal(canSee({kind:'invoices',studentId:'s1'},ctx),true);
assert.equal(canSee({kind:'classes',groupId:'g2'},ctx),false);
assert.equal(canSee({kind:'classes',studentId:'s2'},ctx),false);
assert.equal(canSee({kind:'classes',groupId:'g1'},ctx),true);
assert.equal(canSee({kind:'assignments',groupId:'g1'},ctx),true);
assert.equal(canSee({kind:'staff'},ctx),false);
assert.equal(canSee({kind:'audit'},{...ctx,admin:true}),false);
assert.equal(canSee({kind:'audit'},{...ctx,admin:true,owner:true}),true);
assert.equal(canSee({kind:'admissions',userId:'u1'},{...ctx,student:null}),true);
assert.equal(canSee({kind:'admissions',userId:'u2'},{...ctx,student:null}),false);
const all=[{kind:'students',id:'s1',email:'one@example.com',groupId:'g1',status:'Active'},{kind:'groups',id:'g1',capacity:'1'}];
assert.ok(validateRecord('invoices',{studentId:'s1',amount:100,paid:101},all));
assert.ok(validateRecord('invoices',{studentId:'s1',amount:100,paid:'NaN'},all));
assert.equal(validateRecord('invoices',{studentId:'s1',amount:100,paid:50},all),null);
assert.ok(validateRecord('students',{name:'Two',email:'two@example.com',groupId:'g1',status:'Active'},all));
assert.ok(validateRecord('assessments',{studentId:'s1',score:11,maxScore:10},all));
assert.ok(validateRecord('classes',{title:'Lesson',date:'2027-01-17',time:'10:00',end:'09:00'},all));
assert.ok(validateRecord('resources',{title:'Link',url:'javascript:alert(1)'},all));
